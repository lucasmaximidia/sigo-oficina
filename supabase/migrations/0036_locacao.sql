-- Módulo de Locação (aluguel de scooter/bicicleta elétrica) — uma segunda
-- empresa (VoltCity) operada no mesmo sistema/login da oficina, mas com
-- tabelas e telas próprias, sem se misturar com OS/PDV/Financeiro da
-- oficina. Mesmo padrão de RLS do resto do banco (qualquer usuário
-- autenticado tem acesso total).

create table public.locacao_veiculos (
  id uuid primary key default gen_random_uuid(),
  tipo text not null check (tipo in ('scooter', 'bicicleta')),
  marca text not null,
  modelo text not null,
  cor text,
  chassi text not null unique,
  status text not null default 'disponivel' check (status in ('disponivel', 'alugado', 'manutencao', 'inativo')),
  valor_diaria numeric(10,2),
  observacoes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.locacao_clientes (
  id uuid primary key default gen_random_uuid(),
  nome text not null,
  cpf text,
  telefone text,
  observacoes text,
  created_at timestamptz not null default now()
);

-- Um aluguel por retirada do veículo. data_devolucao_real nula = ainda com
-- o cliente; preenchida = encerrado. O veículo só pode ter um aluguel em
-- aberto (data_devolucao_real nula) por vez — não é reforçado por
-- constraint (como no resto do sistema, a validação fica na camada de
-- ações), pra manter o mesmo padrão já usado em todo o banco.
create table public.locacao_alugueis (
  id uuid primary key default gen_random_uuid(),
  numero integer not null generated by default as identity,
  veiculo_id uuid not null references public.locacao_veiculos(id) on delete restrict,
  cliente_id uuid not null references public.locacao_clientes(id) on delete restrict,
  data_retirada timestamptz not null default now(),
  data_prevista_devolucao timestamptz not null,
  data_devolucao_real timestamptz,
  valor numeric(10,2) not null default 0,
  forma_pagamento text not null check (forma_pagamento in ('pix', 'cartao', 'dinheiro', 'transferencia')),
  status_pagamento text not null default 'pendente' check (status_pagamento in ('pago', 'pendente', 'parcial')),
  valor_pago numeric(10,2) not null default 0,
  data_pagamento date,
  observacoes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index locacao_alugueis_veiculo_id_idx on public.locacao_alugueis(veiculo_id);
create index locacao_alugueis_cliente_id_idx on public.locacao_alugueis(cliente_id);

create table public.locacao_despesas (
  id uuid primary key default gen_random_uuid(),
  data date not null default current_date,
  descricao text not null,
  categoria text,
  fornecedor text,
  forma_pagamento text check (forma_pagamento in ('pix', 'cartao', 'dinheiro', 'transferencia')),
  valor numeric(10,2) not null default 0,
  observacoes text,
  created_at timestamptz not null default now()
);

do $$
declare
  tabela text;
begin
  foreach tabela in array array['locacao_veiculos', 'locacao_clientes', 'locacao_alugueis', 'locacao_despesas']
  loop
    execute format('alter table public.%I enable row level security;', tabela);
    execute format(
      'create policy "Acesso total para usuarios autenticados" on public.%I for all to authenticated using (true) with check (true);',
      tabela
    );
  end loop;
end $$;
